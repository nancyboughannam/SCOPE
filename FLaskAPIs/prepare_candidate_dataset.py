#!/usr/bin/env python3
# ===== SCOPE DATA COLLECTION CHANGE START: new dataset preparation script =====
"""Validate and split SCOPE's candidate-aware window dataset.

The Java orchestrator writes one row per application and configuration window.
This script keeps only finalized windows, verifies the targets, and splits by
independent simulation run so rows from the same run cannot leak across the
training, validation, and test sets.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List

import numpy as np
import pandas as pd


TARGET_COLUMNS = [
    "target_failure_rate",
    "target_deadline_norm_service_time",
]

REQUIRED_COLUMNS = [
    "run_id",
    "policy",
    "num_devices",
    "window_id",
    "window_start",
    "window_end",
    "app_id",
    "candidate_alpha",
    "target_generated",
    "target_completed",
    "target_failed",
    "target_finalized",
    "target_failure_rate",
    "target_deadline_norm_service_time",
    "completion_fraction",
    "is_complete",
]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Prepare candidate-aware SCOPE data for XGBoost."
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("scope_candidate_windows_raw.csv"),
        help="Raw CSV generated by VehicularEdgeOrchestrator.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("scope_candidate_dataset"),
        help="Directory for cleaned train/validation/test CSV files.",
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--test-fraction", type=float, default=0.20)
    parser.add_argument("--validation-fraction", type=float, default=0.20)
    return parser.parse_args()


def validate_columns(frame: pd.DataFrame) -> None:
    missing = [column for column in REQUIRED_COLUMNS if column not in frame.columns]
    if missing:
        raise ValueError(f"Raw dataset is missing required columns: {missing}")

    candidate_w = [f"candidate_w_load_{i}" for i in range(3)]
    candidate_t = [f"candidate_threshold_{i}" for i in range(3)]
    missing_candidates = [
        column for column in candidate_w + candidate_t if column not in frame.columns
    ]
    if missing_candidates:
        raise ValueError(
            f"Raw dataset is missing candidate-action columns: {missing_candidates}"
        )


def clean_rows(frame: pd.DataFrame) -> pd.DataFrame:
    cleaned = frame.copy()
    string_columns = {"run_id", "policy"}
    numeric_columns = [
        column for column in cleaned.columns if column not in string_columns
    ]
    for column in numeric_columns:
        cleaned[column] = pd.to_numeric(cleaned[column], errors="coerce")

    cleaned = cleaned.replace([np.inf, -np.inf], np.nan)
    cleaned = cleaned[
        (cleaned["is_complete"] == 1)
        & (cleaned["completion_fraction"] >= 0.999999)
        & (cleaned["target_generated"] > 0)
        & (cleaned["target_finalized"] > 0)
        & (cleaned["window_start"] >= 250.0)
        ].copy()

    essential = TARGET_COLUMNS + [
        "run_id",
        "num_devices",
        "app_id",
        "candidate_alpha",
    ]
    cleaned = cleaned.dropna(subset=essential)

    invalid_failure = ~cleaned["target_failure_rate"].between(0.0, 1.0)
    invalid_latency = cleaned["target_deadline_norm_service_time"] < 0.0
    if invalid_failure.any() or invalid_latency.any():
        raise ValueError(
            "Targets outside their valid ranges were found: failure rate must be "
            "within [0, 1], and normalized service time must be non-negative."
        )

    return cleaned.sort_values(
        ["run_id", "num_devices", "window_id", "app_id"]
    ).reset_index(drop=True)


def select_feature_columns(frame: pd.DataFrame) -> List[str]:
    features = ["num_devices", "app_id"]
    for column in frame.columns:
        if column.startswith("state_"):
            features.append(column)
        elif column.startswith("previous_"):
            features.append(column)
        elif column.startswith("candidate_"):
            features.append(column)
    return list(dict.fromkeys(features))


def split_run_ids(
    run_ids: List[str], test_fraction: float, validation_fraction: float, seed: int
) -> Dict[str, List[str]]:
    if len(run_ids) < 3:
        raise ValueError(
            "At least three distinct run_id values are required for leakage-free "
            "train/validation/test splits. Run additional independent iterations "
            "with different iteration numbers or -Dscope.runId values."
        )
    if not (0.0 < test_fraction < 1.0 and 0.0 < validation_fraction < 1.0):
        raise ValueError("Split fractions must both be between 0 and 1.")

    shuffled = np.array(sorted(run_ids), dtype=object)
    rng = np.random.default_rng(seed)
    rng.shuffle(shuffled)

    total = len(shuffled)
    test_count = max(1, int(round(total * test_fraction)))
    validation_count = max(1, int(round(total * validation_fraction)))
    if test_count + validation_count >= total:
        test_count = 1
        validation_count = 1

    return {
        "test": shuffled[:test_count].tolist(),
        "validation": shuffled[test_count : test_count + validation_count].tolist(),
        "train": shuffled[test_count + validation_count :].tolist(),
    }


def target_summary(frame: pd.DataFrame) -> Dict[str, Dict[str, float]]:
    summary: Dict[str, Dict[str, float]] = {}
    for target in TARGET_COLUMNS:
        values = frame[target]
        summary[target] = {
            "mean": float(values.mean()),
            "std": float(values.std(ddof=1)) if len(values) > 1 else 0.0,
            "min": float(values.min()),
            "max": float(values.max()),
        }
    return summary


def main() -> None:
    args = parse_args()
    if not args.input.exists():
        raise FileNotFoundError(f"Raw dataset not found: {args.input}")

    raw = pd.read_csv(args.input)
    validate_columns(raw)
    cleaned = clean_rows(raw)
    if cleaned.empty:
        raise ValueError("No complete, finalized training rows remain after cleaning.")

    run_ids = cleaned["run_id"].astype(str).unique().tolist()
    split_ids = split_run_ids(
        run_ids, args.test_fraction, args.validation_fraction, args.seed
    )
    feature_columns = select_feature_columns(cleaned)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    cleaned.to_csv(args.output_dir / "candidate_dataset_clean.csv", index=False)

    split_sizes: Dict[str, int] = {}
    for split_name in ("train", "validation", "test"):
        split_frame = cleaned[cleaned["run_id"].isin(split_ids[split_name])].copy()
        split_frame.to_csv(
            args.output_dir / f"candidate_dataset_{split_name}.csv", index=False
        )
        split_sizes[split_name] = int(len(split_frame))

    action_columns = [
        "candidate_alpha",
        *[f"candidate_w_load_{i}" for i in range(3)],
        *[f"candidate_threshold_{i}" for i in range(3)],
    ]
    action_unique_values = {
        column: int(cleaned[column].nunique(dropna=True)) for column in action_columns
    }
    low_variation_actions = [
        column for column, count in action_unique_values.items() if count < 3
    ]

    schema = {
        "format": "one row per application per candidate-configuration window",
        "feature_columns": feature_columns,
        "target_columns": TARGET_COLUMNS,
        "group_column": "run_id",
        "excluded_rows": "incomplete windows and application-windows with no tasks",
    }
    (args.output_dir / "candidate_feature_schema.json").write_text(
        json.dumps(schema, indent=2), encoding="utf-8"
    )

    report = {
        "raw_rows": int(len(raw)),
        "clean_rows": int(len(cleaned)),
        "distinct_runs": int(len(run_ids)),
        "split_rows": split_sizes,
        "split_run_ids": split_ids,
        "action_unique_values": action_unique_values,
        "low_variation_action_warning": low_variation_actions,
        "targets": target_summary(cleaned),
    }
    (args.output_dir / "candidate_dataset_summary.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8"
    )

    print("Candidate-aware dataset prepared successfully.")
    print(f"  Raw rows:       {len(raw)}")
    print(f"  Clean rows:     {len(cleaned)}")
    print(f"  Distinct runs:  {len(run_ids)}")
    print(f"  Split rows:     {split_sizes}")
    if low_variation_actions:
        print(
            "  WARNING: fewer than three observed values for: "
            + ", ".join(low_variation_actions)
        )


if __name__ == "__main__":
    main()
# ===== SCOPE DATA COLLECTION CHANGE END =====
